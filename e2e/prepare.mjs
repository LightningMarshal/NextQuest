// Runs once before `next dev` in the E2E stack (playwright.config.ts):
//   1. writes .dev.vars.e2e — the Worker "secrets" for this run, all fake
//      (next dev picks it up because NEXT_DEV_WRANGLER_ENV=e2e);
//   2. migrates the throwaway database from empty and seeds the demo group;
//   3. links fake Discord ids to demo people and registers one bot channel,
//      so the Discord bot flow runs end to end against e2e/fake-discord.mjs.
// Never points at a real database: it wipes app data.
import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";

import pg from "pg";

import {
	APP_URL,
	AUTH_SECRET,
	BOT_CHANNEL_ID,
	CRON_SECRET,
	DATABASE_URL,
	DISCORD_IDS,
	FAKE_DISCORD_URL,
	SHIM_PORT,
	STATE_DIR,
} from "./env.mjs";

if (!/localhost|127\.0\.0\.1/.test(new URL(DATABASE_URL).host)) {
	console.error(`Refusing to run E2E against a non-local database (${new URL(DATABASE_URL).host}).`);
	process.exit(1);
}

// The bot's signing key: Discord would hold the private half; here the
// tests do, so they can press buttons with a valid signature.
const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");
const publicKeyHex = publicKey.export({ format: "der", type: "spki" }).subarray(-32).toString("hex");
fs.mkdirSync(STATE_DIR, { recursive: true });
fs.writeFileSync(`${STATE_DIR}discord-private-key.pem`, privateKey.export({ format: "pem", type: "pkcs8" }));

const shim = `http://127.0.0.1:${SHIM_PORT}/sql`;
fs.writeFileSync(
	".dev.vars.e2e",
	[
		"# Generated by e2e/prepare.mjs for the E2E run — fake values only.",
		"NEXTJS_ENV=development",
		`DATABASE_URL=${DATABASE_URL}`,
		`NEON_HTTP_PROXY_ENDPOINT=${shim}`,
		`BETTER_AUTH_SECRET=${AUTH_SECRET}`,
		`BETTER_AUTH_URL=${APP_URL}`,
		"GOOGLE_CLIENT_ID=e2e",
		"GOOGLE_CLIENT_SECRET=e2e",
		"DISCORD_CLIENT_ID=e2e",
		"DISCORD_CLIENT_SECRET=e2e",
		"DISCORD_BOT_TOKEN=e2e-bot-token",
		`DISCORD_PUBLIC_KEY=${publicKeyHex}`,
		`DISCORD_API_BASE=${FAKE_DISCORD_URL}`,
		`CRON_SECRET=${CRON_SECRET}`,
		"",
	].join("\n")
);

const env = { ...process.env, DATABASE_URL, NEON_HTTP_PROXY_ENDPOINT: shim };
const run = (args) => execFileSync("npx", args, { env, stdio: ["ignore", "ignore", "inherit"] });

const pool = new pg.Pool({ connectionString: DATABASE_URL, max: 1 });
// From empty every run: the migration path is part of what's under test.
await pool.query("drop schema if exists public cascade; drop schema if exists drizzle cascade; create schema public;");
run(["drizzle-kit", "migrate"]);
run(["tsx", "scripts/seed.ts"]);

for (const [userId, discordId] of Object.entries(DISCORD_IDS)) {
	await pool.query("insert into account (id, account_id, provider_id, user_id) values ($1, $2, 'discord', $3)", [
		`e2e-discord-${userId}`,
		discordId,
		userId,
	]);
}
// The welcome tour is a modal over every first visit; these people have "seen" it.
await pool.query("update \"user\" set tutorial_seen_at = now()");
await pool.query("insert into discord_bot_channels (name, channel_id, audience) values ('e2e', $1, 'all')", [BOT_CHANNEL_ID]);
await pool.end();
console.log("e2e: database migrated, seeded, and wired to the fake Discord");
